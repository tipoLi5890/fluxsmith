#[test]
fn macro_rail_params_expand_to_power_ports() {
    // Every rail name becomes a power port: a stock name keeps its own glyph, an unknown ground-class
    // name borrows the GND glyph (the Value carries the real net); signals stay labels; the chain's
    // internal node is one wire, not two labels; macro parts are exact (never nudged).
    let l = list(
        serde_json::json!([{"op":"place_rc_filter","x_mil":1000,"y_mil":1000,"in_net":"IN","out_net":"OUT","designators":["R1","C1"],"gnd_net":"GND"}]),
    );
    let ex = sch_ops::expand(&l).unwrap();
    let ports = |ex: &sch_ops::Expanded| -> Vec<(String, String)> {
        ex.ops
            .iter()
            .filter_map(|e| match &e.op {
                sch_ops::Op::PlacePowerPort {
                    lib_id, net_name, ..
                } => Some((lib_id.clone(), net_name.clone())),
                _ => None,
            })
            .collect()
    };
    assert_eq!(
        ports(&ex),
        vec![("power:GND".to_string(), "GND".to_string())]
    );
    let labels = ex
        .ops
        .iter()
        .filter(|e| matches!(e.op, sch_ops::Op::AddNetLabel { .. }))
        .count();
    assert_eq!(labels, 2, "IN and OUT stay labels; the R-C node is a wire");
    assert_eq!(
        ex.ops
            .iter()
            .filter(|e| matches!(e.op, sch_ops::Op::RouteNet { .. }))
            .count(),
        1
    );
    // macro parts are never nudged apart, but they are not "exact": their origin still snaps to the grid
    assert!(ex
        .ops
        .iter()
        .filter(|e| matches!(e.op, sch_ops::Op::PlaceComponent { .. }))
        .all(|e| e.no_nudge && !e.exact));
    let l2 = list(
        serde_json::json!([{"op":"place_rc_filter","x_mil":1000,"y_mil":1000,"in_net":"IN","out_net":"OUT","designators":["R1","C1"],"gnd_net":"AGND_SENSE"}]),
    );
    let ex2 = sch_ops::expand(&l2).unwrap();
    assert_eq!(
        ports(&ex2),
        vec![("power:GND".to_string(), "AGND_SENSE".to_string())]
    );
    // Divider: the mid node is one labelled wire, rails on both ends are ports (VIN borrows VCC).
    let l3 = list(
        serde_json::json!([{"op":"place_divider","x_mil":1000,"y_mil":1000,"top_net":"VIN","mid_net":"VSENSE","bottom_net":"GND","designators":["R1","R2"],"values":["100k","27k"]}]),
    );
    let ex3 = sch_ops::expand(&l3).unwrap();
    assert_eq!(
        ports(&ex3),
        vec![
            ("power:VCC".to_string(), "VIN".to_string()),
            ("power:GND".to_string(), "GND".to_string())
        ]
    );
    assert!(ex3
        .ops
        .iter()
        .any(|e| matches!(&e.op, sch_ops::Op::RouteNet { label: Some(l), .. } if l == "VSENSE")));
    // A spacing below 500 mil would put the mid label on a body: clamped to 500.
    let l4 = list(
        serde_json::json!([{"op":"place_divider","x_mil":1000,"y_mil":1000,"top_net":"VBUS","mid_net":"VSENSE","bottom_net":"GND","designators":["R1","R2"],"values":["1k","1k"],"spacing_mil":400}]),
    );
    let ex4 = sch_ops::expand(&l4).unwrap();
    let ys: Vec<i64> = ex4
        .ops
        .iter()
        .filter_map(|e| match &e.op {
            sch_ops::Op::PlaceComponent {
                place: sch_ops::Place::At(p),
                ..
            } => Some(p.y),
            _ => None,
        })
        .collect();
    assert_eq!(ys[1] - ys[0], sch_model::mil_to_nm(500.0));
    assert_eq!(sch_ops::power_glyph("-7V"), "VEE");
    assert_eq!(sch_ops::power_glyph("-5V"), "-5V");
    assert_eq!(sch_ops::power_glyph("PGND"), "GND");
    assert_eq!(sch_ops::power_glyph("+3V3"), "+3V3");
}

