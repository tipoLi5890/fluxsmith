use sch_ops::{expand, template, Op, OpList, CORE_OPS, MACRO_OPS, PROTOCOL_VERSION};
use serde_json::{json, Map, Value};
use std::path::PathBuf;

fn sorted(v: Value) -> Value {
    match v {
        Value::Object(m) => {
            let mut b: Vec<(String, Value)> = m.into_iter().map(|(k, v)| (k, sorted(v))).collect();
            b.sort_by(|a, c| a.0.cmp(&c.0));
            Value::Object(b.into_iter().collect::<Map<String, Value>>())
        }
        Value::Array(a) => Value::Array(a.into_iter().map(sorted).collect()),
        other => other,
    }
}

/// The op vocabulary as a JSON document: every op name, its full and required-only field
/// templates, whether it is a macro and whether it is structural. This is what the harness
/// and the docs (`docs/opspec-v1.md`) pin against.
fn schema() -> Value {
    let mut ops = Map::new();
    for (kind, names) in [("core", CORE_OPS), ("macro", MACRO_OPS)] {
        for name in names {
            let full = template(name, false).unwrap_or_else(|| panic!("no template for {name}"));
            let required =
                template(name, true).unwrap_or_else(|| panic!("no required template for {name}"));
            let structural = {
                let list = OpList {
                    protocol_version: PROTOCOL_VERSION,
                    target_format: "kicad".into(),
                    groups: Default::default(),
                    sheets: Default::default(),
                    ops: vec![full.clone()],
                };
                expand(&list)
                    .ok()
                    .map(|e| e.ops.iter().any(|o| o.op.is_structural()))
            };
            ops.insert(
                name.to_string(),
                json!({ "kind": kind, "fields": full, "required": required, "structural": structural }),
            );
        }
    }
    sorted(json!({
        "$comment": "Generated by crates/sch-ops/tests/schema_and_regressions.rs; regenerate with FLUXSMITH_UPDATE_SCHEMA=1 cargo test -p sch-ops. Field names/values are the op templates of opspec v1.",
        "protocol_version": PROTOCOL_VERSION,
        "core_ops": CORE_OPS,
        "macro_ops": MACRO_OPS,
        "ops": ops,
    }))
}

fn schema_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../tests/conformance/ops.v1.schema.json")
}

#[test]
fn ops_v1_schema_matches_checked_in_file() {
    let want = serde_json::to_string_pretty(&schema()).unwrap() + "\n";
    let path = schema_path();
    if std::env::var("FLUXSMITH_UPDATE_SCHEMA")
        .map(|v| v == "1")
        .unwrap_or(false)
    {
        std::fs::write(&path, &want).unwrap();
        return;
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert_eq!(
        have, want,
        "opspec v1 drifted from tests/conformance/ops.v1.schema.json — this is a protocol change: bump/annotate docs/opspec-v1.md and regenerate with FLUXSMITH_UPDATE_SCHEMA=1"
    );
}

