/// opspec v1 has one label op: the scope is a field, not a name. `add_global_label` /
/// `add_hier_label` are aliases the harness rewrites (`src/agent/tools/ops.ts`), and the scope the
/// alias states must arrive here as `scope`, because the engine defaults to `local` — a
/// cross-sheet interface authored as `add_hier_label` and normalised without its scope would
/// become a sheet-local label that joins nothing.
#[test]
fn reg_label_scope_is_a_field_and_defaults_to_local() {
    let parse = |op: Value| -> Result<String, Vec<sch_ops::OpError>> {
        let list = OpList::from_value(json!({"protocol_version": PROTOCOL_VERSION, "ops": [op]}))
            .map_err(|e| vec![e])?;
        let mut ex = expand(&list)?;
        match ex.ops.remove(0).op {
            Op::AddNetLabel { scope, .. } => Ok(format!("{scope:?}")),
            other => panic!("not a label op: {other:?}"),
        }
    };
    let at = json!({"op": "add_net_label", "name": "VOUT", "at": "U1.1"});
    assert_eq!(parse(at.clone()).unwrap(), "Local");
    for (scope, want) in [("global", "Global"), ("hierarchical", "Hierarchical")] {
        let mut op = at.clone();
        op["scope"] = json!(scope);
        assert_eq!(parse(op).unwrap(), want);
    }
    // Nothing else is a scope: a misspelling is refused, never silently local (the harness
    // normalises `hier` to `hierarchical` before the engine sees it).
    let mut bad = at;
    bad["scope"] = json!("hier");
    let err = parse(bad).expect_err("`hier` must not parse as a scope");
    assert_eq!(err[0].code, "OPLIST_CONSTRAINT");
    // `add_global_label` / `add_hier_label` are not ops of the vocabulary.
    for n in ["add_global_label", "add_hier_label"] {
        assert!(!CORE_OPS.contains(&n) && !MACRO_OPS.contains(&n), "{n}");
    }
}

/// `place_array` terminates each element's pins: `pinN_labels` one net per element (alias
/// `pinN_nets`), `pinN_rail` the same rail on all of them as a power port. Before this the macro
/// took neither and a real model's `pin1_labels` / `pin2_rail` were dropped without a word, so
/// every pin of the array floated.
#[test]
fn reg_place_array_wires_each_element() {
    let ex = expand(&list(json!([{
        "op": "place_array", "lib_id": "Device:R", "designator_prefix": "R", "count": 4,
        "x_mil": 3000, "y_mil": 3000, "pitch_mil": 400, "direction": "right", "value": "10k",
        "pin1_labels": ["IN0", "IN1", "IN2", "IN3"], "pin2_rail": "GND"
    }])))
    .unwrap();
    assert!(ex.warnings.is_empty(), "{:?}", ex.warnings);
    // 4 x (component, label on pin 1, power port on pin 2), in element order.
    assert_eq!(ex.ops.len(), 12);
    assert_eq!(ex.mapping, vec![(0..12).collect::<Vec<_>>()]);
    for (k, chunk) in ex.ops.chunks(3).enumerate() {
        match &chunk[0].op {
            Op::PlaceComponent { designator, .. } => assert_eq!(*designator, format!("R{}", k + 1)),
            other => panic!("{other:?}"),
        }
        match &chunk[1].op {
            Op::AddNetLabel {
                name, at, scope, ..
            } => {
                assert_eq!(*name, format!("IN{k}"));
                assert_eq!(*scope, sch_ops::Scope::Local);
                assert_eq!(
                    *at,
                    sch_ops::Anchor::Endpoint(sch_ops::Endpoint::Pin {
                        reference: format!("R{}", k + 1),
                        unit: None,
                        pin: "1".into()
                    })
                );
            }
            other => panic!("{other:?}"),
        }
        match &chunk[2].op {
            Op::PlacePowerPort {
                lib_id, net_name, ..
            } => {
                assert_eq!(lib_id, "power:GND");
                assert_eq!(net_name, "GND");
            }
            other => panic!("{other:?}"),
        }
        // Macro parts and their terminations are designed geometry: never nudged apart.
        assert!(chunk.iter().all(|o| o.no_nudge));
    }
    // `pin1_nets` is the same field; `pin2_labels` works on the other pin; an explicit scope keeps
    // a rail-looking name a label of that scope instead of a power port.
    let ex = expand(&list(json!([{
        "op": "place_array", "lib_id": "Device:R", "designator_prefix": "R", "count": 2,
        "x_mil": 0, "y_mil": 0, "pin1_rail": "+3V3", "pin2_nets": ["A", "B"], "pin2_scope": "global"
    }])))
    .unwrap();
    assert_eq!(ex.ops.len(), 6);
    assert!(
        matches!(&ex.ops[1].op, Op::PlacePowerPort { lib_id, net_name, .. } if lib_id == "power:+3V3" && net_name == "+3V3")
    );
    assert!(
        matches!(&ex.ops[2].op, Op::AddNetLabel { name, scope, .. } if name == "A" && *scope == sch_ops::Scope::Global)
    );
    // A rail name in the label list still becomes a power port (red line 4).
    let ex = expand(&list(json!([{
        "op": "place_array", "lib_id": "Device:R", "designator_prefix": "R", "count": 1,
        "x_mil": 0, "y_mil": 0, "pin2_labels": ["GND"]
    }])))
    .unwrap();
    assert!(matches!(&ex.ops[1].op, Op::PlacePowerPort { net_name, .. } if net_name == "GND"));
}

/// A label or a power port sticks out along the pin axis, so a wired array that marches that way
/// is clamped the way the chain macros clamp `spacing_mil`. Across the pins nothing changes.
#[test]
fn place_array_clamps_pitch_only_along_the_pin_axis() {
    let pts = |ex: &sch_ops::Expanded| -> Vec<sch_model::Pt> {
        ex.ops
            .iter()
            .filter_map(|e| match &e.op {
                Op::PlaceComponent {
                    place: sch_ops::Place::At(p),
                    ..
                } => Some(*p),
                _ => None,
            })
            .collect()
    };
    let down = expand(&list(json!([{
        "op": "place_array", "lib_id": "Device:R", "designator_prefix": "R", "count": 2,
        "x_mil": 0, "y_mil": 0, "pitch_mil": 400, "direction": "down", "pin2_rail": "GND"
    }])))
    .unwrap();
    let p = pts(&down);
    assert_eq!(p[1].y - p[0].y, sch_model::mil_to_nm(700.0));
    // The same array without wiring keeps the pitch it was given.
    let bare = expand(&list(json!([{
        "op": "place_array", "lib_id": "Device:R", "designator_prefix": "R", "count": 2,
        "x_mil": 0, "y_mil": 0, "pitch_mil": 400, "direction": "down"
    }])))
    .unwrap();
    assert_eq!(pts(&bare)[1].y, sch_model::mil_to_nm(400.0));
    // Across the pin axis (the usual row of vertical passives) 400 mil stays 400 mil.
    let right = expand(&list(json!([{
        "op": "place_array", "lib_id": "Device:R", "designator_prefix": "R", "count": 2,
        "x_mil": 0, "y_mil": 0, "pitch_mil": 400, "direction": "right", "pin2_rail": "GND"
    }])))
    .unwrap();
    assert_eq!(pts(&right)[1].x, sch_model::mil_to_nm(400.0));
}

/// Lengths are checked against `count`, and the two spellings of the same field are refused
/// together: a half-wired array is worse than a refusal the model can fix.
#[test]
fn place_array_wiring_lengths_are_validated() {
    let base = |extra: Value| {
        let mut o = json!({"op": "place_array", "lib_id": "Device:R", "designator_prefix": "R",
                           "count": 4, "x_mil": 0, "y_mil": 0});
        let m = o.as_object_mut().unwrap();
        for (k, v) in extra.as_object().unwrap() {
            m.insert(k.clone(), v.clone());
        }
        list(json!([o]))
    };
    for (extra, needle) in [
        (
            json!({"pin1_labels": ["A", "B"]}),
            "one net name per element",
        ),
        (json!({"pin1_labels": ["A", "B", "", "D"]}), "is empty"),
        (
            json!({"pin1_labels": ["A", "B", "C", "D"], "pin1_nets": ["A", "B", "C", "D"]}),
            "not both",
        ),
        (
            json!({"pin2_labels": ["A", "B", "C", "D"], "pin2_rail": "GND"}),
            "pin 2 carries one net",
        ),
        (
            json!({"pin1_scope": "sideways"}),
            "local/global/hierarchical",
        ),
    ] {
        let errs = expand(&base(extra.clone())).unwrap_err();
        assert_eq!(errs[0].code, "OPLIST_CONSTRAINT", "{extra} -> {errs:?}");
        assert!(errs[0].message.contains(needle), "{extra} -> {errs:?}");
    }
}

/// reg: a field no branch reads was dropped in silence, so a model that invented `pin1_labels`
/// got an unwired array and no explanation. The parser now reports it as a warning (the op-list
/// still expands), which is what the model needs to correct itself.
#[test]
fn reg_unknown_fields_are_reported_not_swallowed() {
    let ex = expand(&list(json!([
        {"op": "place_array", "lib_id": "Device:R", "designator_prefix": "R", "count": 2,
         "x_mil": 0, "y_mil": 0, "pin1_labels": ["A", "B"], "pin2_raill": "GND", "colour": "red"},
        {"op": "add_junction", "at": [0, 0]}
    ])))
    .unwrap();
    assert_eq!(ex.ops.len(), 5, "the op-list still expands");
    let msgs: Vec<&str> = ex.warnings.iter().map(|w| w.message.as_str()).collect();
    assert_eq!(msgs.len(), 2, "{msgs:?}");
    assert!(ex
        .warnings
        .iter()
        .all(|w| w.index == 0 && w.code == "OPLIST_UNKNOWN_FIELD"));
    // Sorted by field name; each message names the op and lists the fields it does have.
    assert!(msgs[0].starts_with("unknown field `colour` on `place_array` was ignored (known: "));
    assert!(msgs[0].contains("pin1_labels"), "{}", msgs[0]);
    assert!(msgs[1].contains("`pin2_raill`"), "{}", msgs[1]);
    assert!(ex.warnings[1]
        .remediation
        .as_deref()
        .unwrap()
        .contains("ops.template"));
    // The envelope's own fields are never unknown.
    let ex = expand(
        &OpList::from_value(json!({"protocol_version": 1,
        "groups": {"g": {"origin_mil": [0, 0]}}, "sheets": {"p": "p.kicad_sch"},
        "ops": [{"op": "add_junction", "at": [0, 0], "group": "g", "sheet": "p", "note": "n", "exact": true}]}))
        .unwrap(),
    )
    .unwrap();
    assert!(ex.warnings.is_empty(), "{:?}", ex.warnings);
}

/// Guard against the two lists drifting apart: every field of every `template()` must be a field
/// the parser reads, or the unknown-field warning would fire on the engine's own example.
#[test]
fn no_template_field_is_reported_unknown() {
    for op in CORE_OPS.iter().chain(MACRO_OPS.iter()) {
        let l = if *op == "arrange_group" {
            // The template leaves the group name empty; declare it so the op expands.
            OpList::from_value(json!({"protocol_version": 1,
                "groups": {"": {"origin_mil": [0, 0]}},
                "ops": [template(op, false).unwrap()]}))
            .unwrap()
        } else {
            list(json!([template(op, false).unwrap()]))
        };
        if let Ok(ex) = expand(&l) {
            assert!(ex.warnings.is_empty(), "{op}: {:?}", ex.warnings);
        }
    }
}

/// reg: `place_vcc` / `place_gnd` without a `lib_id` drew `power:VCC` for every rail, so a real
/// Build run put four VCC glyphs on a VBUS rail although `power:VBUS` exists. The glyph now
/// follows the net name through the one borrow rule (`power_glyph`), and says so when it borrows.
#[test]
fn reg_rail_port_glyph_follows_the_net_name() {
    let port = |ops: Value| -> (String, String, Vec<String>) {
        let ex = expand(&list(ops)).unwrap();
        let (lib_id, net_name) = ex
            .ops
            .iter()
            .find_map(|e| match &e.op {
                Op::PlacePowerPort {
                    lib_id, net_name, ..
                } => Some((lib_id.clone(), net_name.clone())),
                _ => None,
            })
            .expect("a power port");
        (
            lib_id,
            net_name,
            ex.warnings.iter().map(|w| w.code.clone()).collect(),
        )
    };
    // A stock rail gets its own glyph, silently.
    for (net, glyph) in [
        ("VBUS", "power:VBUS"),
        ("+3V3", "power:+3V3"),
        ("GND", "power:GND"),
        ("VCC", "power:VCC"),
    ] {
        let (lib_id, name, warns) = port(json!([{"op":"place_vcc","at":"C1.1","net_name":net}]));
        assert_eq!((lib_id.as_str(), name.as_str()), (glyph, net));
        assert!(warns.is_empty(), "{net}: {warns:?}");
    }
    // A rail KiCad has no symbol for borrows the nearest glyph and says which one. The Value
    // keeps the real name, which is the name KiCad reads the net from.
    for (net, glyph) in [
        ("USB_5V", "power:+5V"),
        ("MYRAIL", "power:VCC"),
        ("SENSOR_GND", "power:GND"),
        ("-9V_BIAS", "power:-9V"),
    ] {
        let (lib_id, name, warns) = port(json!([{"op":"place_vcc","at":"C1.1","net_name":net}]));
        assert_eq!((lib_id.as_str(), name.as_str()), (glyph, net));
        assert_eq!(
            warns,
            vec!["OPLIST_RAIL_GLYPH_BORROWED".to_string()],
            "{net}"
        );
    }
    // `place_gnd` shares the rule and its own default is silent.
    let (lib_id, name, warns) = port(json!([{"op":"place_gnd","at":"C1.2"}]));
    assert_eq!((lib_id.as_str(), name.as_str()), ("power:GND", "GND"));
    assert!(warns.is_empty(), "{warns:?}");
    // An explicit lib_id still wins.
    let (lib_id, ..) =
        port(json!([{"op":"place_vcc","at":"C1.1","net_name":"VBUS","lib_id":"power:VCC"}]));
    assert_eq!(lib_id, "power:VCC");

    // The borrow itself: a stock rail carried as a whole token, longest first; digits that run
    // into a letter are not a rail name.
    for (rail, glyph) in [
        ("USB_5V", "+5V"),
        ("USB_5VA", "+5VA"),
        ("VDD_3V3", "+3V3"),
        ("3.3V_SENSE", "+3.3V"),
        ("-12V_FAN", "-12V"),
        ("VCC5V", "VCC"),
        ("AUX15V", "VCC"),
        ("MYRAIL", "VCC"),
        ("-7V", "VEE"),
        ("PGND", "GND"),
        ("+3V3", "+3V3"),
    ] {
        assert_eq!(sch_ops::power_glyph(rail), glyph, "glyph for {rail}");
    }
}
